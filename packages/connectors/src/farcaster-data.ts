import { parseAddress } from '@olcys/core';

/**
 * Farcaster: an open social network whose accounts live on a public protocol. An account can attach wallets
 * to itself, and each attachment is a claim signed by the wallet's own key — stored with the account, for anyone to check.
 */
export const FARCASTER_API = 'https://api.farcaster.xyz';
export const FARCASTER_NODE = 'https://snap.farcaster.xyz:3381';
/** Farcaster counts time in seconds from the start of 2021. */
const EPOCH = Date.UTC(2021, 0, 1);
export const farcasterTime = (seconds: number): string => new Date(EPOCH + seconds * 1000).toISOString();

export interface FarcasterProfile {
  fid: number;
  username?: string;
  displayName?: string;
  bio?: string;
  location?: string;
  url?: string;
  followers: number;
  following: number;
  /** Ethereum wallets the account attached to itself (each backed by a signed claim). */
  wallets: string[];
  /** The address that owns the account registration; usually generated by the app, not the person's own wallet. */
  custody?: string;
  /** Accounts on other services the person connected, e.g. { platform: "x", username: "…" }. */
  connected: { platform: string; username: string }[];
}

type Json = Record<string, any>;

/** Reads a profile from the client API's answer: either the full "user-by-fid" result or one entry of a follow list. */
export function parseFarcasterUser(json: Json | undefined): FarcasterProfile | undefined {
  const u: Json | undefined = json?.result?.user ?? (json?.fid ? json : undefined);
  if (!u?.fid) return undefined;
  const extras: Json = json?.result?.extras ?? {};
  const clean = (s: unknown) => (typeof s === 'string' && s.replace(/[​-‍﻿]/g, '').trim()) || undefined;
  return {
    fid: Number(u.fid),
    username: clean(u.username),
    displayName: clean(u.displayName),
    bio: clean(u.profile?.bio?.text),
    location: clean(u.profile?.location?.description),
    url: clean(u.profile?.url),
    followers: Number(u.followerCount ?? 0),
    following: Number(u.followingCount ?? 0),
    wallets: ((extras.ethWallets ?? []) as string[]).map((a) => parseAddress(a)?.address).filter((a): a is string => !!a),
    custody: parseAddress(String(extras.custodyAddress ?? ''))?.address,
    connected: ((u.connectedAccounts ?? []) as Json[]).filter((c) => c.username && !c.expired).map((c) => ({ platform: String(c.platform), username: String(c.username) })),
  };
}

export interface FarcasterWalletClaim {
  address: string;
  blockHash: string;
  /** Signature of the claim by the wallet's key (base64). */
  signature: string;
  /** 0 = an ordinary address; 1 = a contract wallet, whose signature cannot be checked off-chain. */
  type: number;
  at: string;
}

/** Signed wallet claims of an account, as the protocol node returns them. Only Ethereum claims are kept. */
export function parseFarcasterClaims(json: Json | undefined): FarcasterWalletClaim[] {
  const out: FarcasterWalletClaim[] = [];
  for (const m of (json?.messages ?? []) as Json[]) {
    const b = m.data?.verificationAddAddressBody;
    const address = b?.protocol === 'PROTOCOL_ETHEREUM' ? parseAddress(String(b.address))?.address : undefined;
    if (!address) continue;
    out.push({ address, blockHash: String(b.blockHash), signature: String(b.claimSignature), type: Number(b.type ?? 0), at: farcasterTime(Number(m.data.timestamp)) });
  }
  return out;
}

export interface FarcasterCast {
  hash: string;
  at: string;
  text: string;
  /** Channel the post was made in, if any. */
  channel?: string;
  /** True for a reply to someone else's post. */
  reply: boolean;
}

export function parseFarcasterCasts(json: Json | undefined): FarcasterCast[] {
  const out: FarcasterCast[] = [];
  for (const m of (json?.messages ?? []) as Json[]) {
    const b = m.data?.castAddBody;
    if (!b || typeof b.text !== 'string' || !b.text.trim()) continue;
    out.push({ hash: String(m.hash), at: farcasterTime(Number(m.data.timestamp)), text: b.text, channel: typeof b.parentUrl === 'string' ? b.parentUrl : undefined, reply: !!b.parentCastId });
  }
  return out;
}

/**
 * Reads a profile from the protocol node's answer (the account's own signed "user data" messages).
 * The node holds the same facts as the client API, with the stated location as coordinates ("geo:52.23,21.01").
 */
export function parseFarcasterUserData(json: Json | undefined, fid: number): (FarcasterProfile & { geo?: string }) | undefined {
  const values: Record<string, string> = {};
  for (const m of (json?.messages ?? []) as Json[]) {
    const b = m.data?.userDataBody;
    if (b?.type && typeof b.value === 'string') values[String(b.type)] = b.value;
  }
  if (!Object.keys(values).length) return undefined;
  const clean = (s: string | undefined) => (s && s.replace(/[\u200b-\u200d\ufeff]/g, '').trim()) || undefined;
  const connected: { platform: string; username: string }[] = [];
  if (clean(values.USER_DATA_TYPE_TWITTER)) connected.push({ platform: 'x', username: clean(values.USER_DATA_TYPE_TWITTER)! });
  if (clean(values.USER_DATA_TYPE_GITHUB)) connected.push({ platform: 'github', username: clean(values.USER_DATA_TYPE_GITHUB)! });
  const primary = parseAddress(values.USER_DATA_PRIMARY_ADDRESS_ETHEREUM ?? '')?.address;
  return {
    fid, username: clean(values.USER_DATA_TYPE_USERNAME), displayName: clean(values.USER_DATA_TYPE_DISPLAY), bio: clean(values.USER_DATA_TYPE_BIO),
    url: clean(values.USER_DATA_TYPE_URL), geo: clean(values.USER_DATA_TYPE_LOCATION), followers: 0, following: 0, wallets: primary ? [primary] : [], connected,
  };
}
